function russianNumberForm(number, singular, genitive, plural) {
  const lastTwo = number % 100;
  const last = number % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return plural;
  if (last === 1) return singular;
  if (last >= 2 && last <= 4) return genitive;
  return plural;
}

function translatePlaceValue(prompt) {
  const match = prompt.match(/^(\d+) (עשרת|עשרות) ו-(\d+) אחדות = ___$/);
  if (!match) return null;
  const tens = Number(match[1]);
  const ones = Number(match[3]);
  const tensEn = tens === 1 ? 'ten' : 'tens';
  const onesEn = ones === 1 ? 'one' : 'ones';
  const tensRu = russianNumberForm(tens, 'десяток', 'десятка', 'десятков');
  const onesRu = russianNumberForm(ones, 'единица', 'единицы', 'единиц');
  return {
    he: prompt,
    en: `${tens} ${tensEn} and ${ones} ${onesEn} = ___`,
    ru: `${tens} ${tensRu} и ${ones} ${onesRu} = ___`
  };
}

function evaluateMathExpression(expression) {
  const tokens = expression.match(/\d+|[()+−×:]/g);
  let index = 0;

  function parsePrimary() {
    if (tokens[index] === '(') {
      index++;
      const value = parseSum();
      if (tokens[index] !== ')') throw new Error(`Invalid math expression: ${expression}`);
      index++;
      return value;
    }
    const token = tokens[index++];
    if (!/^\d+$/.test(token || '')) throw new Error(`Invalid math expression: ${expression}`);
    return Number(token);
  }

  function parseProduct() {
    let value = parsePrimary();
    while (tokens[index] === '×' || tokens[index] === ':') {
      const operator = tokens[index++];
      const right = parsePrimary();
      value = operator === '×' ? value * right : value / right;
    }
    return value;
  }

  function parseSum() {
    let value = parseProduct();
    while (tokens[index] === '+' || tokens[index] === '−') {
      const operator = tokens[index++];
      const right = parseProduct();
      value = operator === '+' ? value + right : value - right;
    }
    return value;
  }

  const result = parseSum();
  if (index !== tokens.length) throw new Error(`Invalid math expression: ${expression}`);
  return result;
}

function getMathAnswer(prompt) {
  const placeValue = prompt.match(/^(\d+) עשר(?:ת|ות) ו-(\d+) אחדות/);
  if (placeValue) return Number(placeValue[1]) * 10 + Number(placeValue[2]);

  const [expression, resultText] = prompt.split('=').map(part => part.trim());
  if (expression.includes('___')) {
    const missing = expression.match(/^(\d+)\s*([+−×:])\s*___$/);
    if (!missing) throw new Error(`Unsupported missing-value question: ${prompt}`);
    const left = Number(missing[1]);
    const result = Number(resultText);
    switch (missing[2]) {
      case '+': return result - left;
      case '−': return left - result;
      case '×': return result / left;
      case ':': return left / result;
    }
  }
  return evaluateMathExpression(expression);
}

function buildMathTopics(age) {
  return mathPrompts[age].map(topic => topic.split('|').map(prompt => {
    const q = translatePlaceValue(prompt) || { he: prompt, en: prompt, ru: prompt };
    const answer = String(getMathAnswer(prompt));
    return { q, a: { he: answer, en: answer, ru: answer } };
  }));
}

